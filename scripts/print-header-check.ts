/**
 * Prints a browser-console check of the live security and indexing headers.
 * The expected values come from src/config/security.ts, so the check cannot
 * drift from the code. Hosted deploys are behind Netlify team login, so the
 * owner pastes the output into the console of a logged-in tab:
 *
 *   npm run print:header-check   (then paste the printed script)
 *
 * Works on a deploy preview, the netlify.app alias or www.trip-range.com, and
 * decides from the host which indexing rule applies.
 */
import { canonicalHost, securityHeaders } from "../src/config/security";

export function headerCheckScript() {
  const expected = Object.fromEntries(
    securityHeaders(true).map((h) => [h.key.toLowerCase(), h.value]),
  );
  return `(async () => {
  // Generated by scripts/print-header-check.ts from src/config/security.ts.
  const EXPECTED = ${JSON.stringify(expected, null, 2)};
  const CANONICAL = ${JSON.stringify(canonicalHost)};
  const host = location.hostname;
  const kind = host === CANONICAL ? "canonical" : /^deploy-preview-\\d+--/.test(host) ? "preview" : "alias";
  const indexable = ["/", "/about", "/methodology"];
  const paths = ["/", "/about", "/methodology", "/plan", "/privacy", "/robots.txt", "/sitemap.xml", "/api/health", "/icon.svg"];
  const rows = [];
  const check = async (path, informational = false) => {
    let r;
    try {
      r = await fetch(path, { cache: "no-store", credentials: "include", redirect: "manual" });
    } catch (e) {
      rows.push({ path, status: "error", verdict: "INCONCLUSIVE", problems: String(e) });
      return;
    }
    if (r.type === "opaqueredirect" || (r.status >= 300 && r.status < 400)) {
      rows.push({ path, status: r.status || "redirect", verdict: "INCONCLUSIVE", problems: "redirected (logged in?)" });
      return;
    }
    const problems = [];
    for (const [name, value] of Object.entries(EXPECTED))
      if (r.headers.get(name) !== value) problems.push(name + (r.headers.get(name) === null ? " missing" : " differs"));
    const hsts = r.headers.get("strict-transport-security") || "";
    const maxAge = Number((hsts.match(/max-age=(\\d+)/) || [])[1] || 0);
    if (maxAge < 31536000) problems.push("HSTS missing or under one year");
    if (r.headers.get("x-powered-by")) problems.push("x-powered-by present");
    const robots = r.headers.get("x-robots-tag") || "";
    if (kind === "canonical" && indexable.includes(path) && /noindex/i.test(robots)) problems.push("indexable page is noindex");
    if (kind !== "canonical" && !/noindex/i.test(robots)) problems.push(kind + " host is not noindex");
    rows.push({
      path,
      status: r.status,
      "x-robots-tag": robots || null,
      hsts: hsts || null,
      verdict: problems.length ? (informational ? "INFO" : "FAIL") : "PASS",
      problems: problems.join("; ") || null,
    });
  };
  for (const path of paths) await check(path);
  // A static asset: reported for information, since the CDN may serve it with its own headers.
  const html = await (await fetch("/", { credentials: "include", cache: "no-store" })).text();
  const asset = (html.match(/\\/_next\\/static\\/[^"']+\\.js/) || [])[0];
  if (asset) await check(asset, true);
  console.log("Host:", host, "| treated as:", kind);
  console.table(rows);
  const failed = rows.filter((x) => x.verdict === "FAIL").length;
  const unsure = rows.filter((x) => x.verdict === "INCONCLUSIVE").length;
  console.log(failed ? "FAIL: " + failed + " responses" : unsure ? "INCONCLUSIVE: " + unsure + " responses could not be read" : "PASS: every response has the expected headers");
  console.log(JSON.stringify({ host, kind, checkedAt: new Date().toISOString(), rows }));
})();`;
}

if (require.main === module) console.log(headerCheckScript());
