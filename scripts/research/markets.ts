export function researchCurrency(market: ResearchMarket): {
  currency: CurrencyCode;
  nativeReady: boolean;
} {
  return isCurrency(market.nativeCurrency)
    ? { currency: market.nativeCurrency, nativeReady: true }
    : { currency: "USD", nativeReady: false };
}
export function researchOrigin(market: ResearchMarket): TravelLocation {
  return {
    id: market.id,
    name: market.name,
    type: "city",
    cityCode: market.code,
    iataCodes: [market.code],
    countryCode: market.country,
    countryName: { en: market.country, sq: market.country },
  };
}
