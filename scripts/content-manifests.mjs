/** Build/operator only; safe per-file bounds, no maximum number of persisted destinations. */
export function readManifestRecords(directory, key) {
  const stat = lstatSync(directory);
  if (!stat.isDirectory() || stat.isSymbolicLink())
    throw Error("invalid-record-directory");
  const files = readdirSync(directory)
    .filter((name) => name.endsWith(".json"))
    .sort();
  const seen = new Set();
  return files.map((file) => {
    if (!/^[a-zA-Z0-9][a-zA-Z0-9_-]{0,119}\.json$/.test(file))
      throw Error("invalid-record-filename");
    const path = join(directory, file),
      stat = lstatSync(path);
    if (!stat.isFile() || stat.isSymbolicLink() || stat.size > 256000)
      throw Error("invalid-record-file");
    const raw = readFileSync(path, "utf8");
    if (Buffer.byteLength(raw) > 256000) throw Error("record-byte-limit");
    const record = JSON.parse(raw),
      id = record?.[key];
    if (
      typeof id !== "string" ||
      !/^[a-zA-Z0-9][a-zA-Z0-9:_-]{0,119}$/.test(id) ||
      seen.has(id)
    )
      throw Error("invalid-or-duplicate-record-id");
    seen.add(id);
    return { file, record };
  });
}
export function manifestText(spec, entries) {
  return (
    `// Generated by npm run generate:content-manifests. Do not edit; generation never approves records.\nimport type { ${spec.type} } from "${spec.typePath}";\n` +
    entries
      .map(({ file }, i) => `import record${i} from "./${file}";\n`)
      .join("") +
    `\nexport const ${spec.name} = {\n  schemaVersion: 1,\n  records: [${entries.map((_, i) => `record${i}`).join(", ")}],\n} as ${spec.type};\n`
  );
}
export function runManifests(check, root = process.cwd()) {
  for (const spec of manifests) {
    const directory = join(root, spec.directory),
      output = join(directory, "records.ts");
    const text = manifestText(spec, readManifestRecords(directory, spec.key));
    if (check) {
      if (readFileSync(output, "utf8") !== text)
        throw Error("static-manifest-drift");
    } else writeFileSync(output, text);
  }
}
if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  try {
    const args = process.argv.slice(2);
    if (args.length !== 1 || !["--check", "--write"].includes(args[0]))
      throw Error("arguments");
    runManifests(args[0] === "--check");
    console.log(
      `Static manifests ${args[0] === "--check" ? "verified (writes: 0)" : "generated"}; external calls: 0; approvals: 0.`,
    );
  } catch {
    console.error(
      "Manifest validation failed: invalid records, duplicate IDs or drift. Run generate:content-manifests after reviewing source records.",
    );
    process.exitCode = 1;
  }
}
